// Refreshes src/lib/nearby/osm-places.gen.ts: OpenStreetMap's motorcycle parking within RADIUS_M of
// CAMPUS, fetched once from the Overpass API and committed, so the page never waits on Overpass.
// Review the diff before committing; anyone can edit OpenStreetMap.
// OVERPASS_URL picks another Overpass instance when the main one is busy.
import { writeFile } from "node:fs/promises";

import { overpassQuery, osmPlaces } from "../src/lib/nearby/osm.ts";
import { CAMPUS, RADIUS_M } from "../src/lib/nearby/places.ts";

const OUTPUT = new URL("../src/lib/nearby/osm-places.gen.ts", import.meta.url);

async function main() {
  const endpoint = process.env.OVERPASS_URL?.trim() || "https://overpass-api.de/api/interpreter";
  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded", "User-Agent": "nearby-osm-snapshot/1.0" },
    body: new URLSearchParams({ data: overpassQuery(CAMPUS, RADIUS_M) }),
    signal: AbortSignal.timeout(90_000),
  });
  if (!response.ok) throw new Error(`Overpass answered ${response.status}; retry later or set OVERPASS_URL`);
  const body: unknown = await response.json();
  const places = osmPlaces(body, CAMPUS, RADIUS_M);
  const base = (body as { osm3s?: { timestamp_osm_base?: unknown } }).osm3s?.timestamp_osm_base;
  const lines = [
    "// Generated by scripts/nearby-osm.ts; do not edit. Run `pnpm nearby:osm` to refresh.",
    "// Data © OpenStreetMap contributors, available under the Open Database License (ODbL).",
    'import type { OsmPlace } from "./places.ts";',
    "",
    `export const OSM_BASE = ${JSON.stringify(typeof base === "string" ? base : null)};`,
    "",
    "export const OSM_PLACES: readonly OsmPlace[] = [",
    ...places.map((place) => `  ${JSON.stringify(place)},`),
    "];",
    "",
  ];
  await writeFile(OUTPUT, lines.join("\n"));
  console.log(`Wrote ${places.length} place(s) from OpenStreetMap as of ${base ?? "an unknown time"}.`);
}

await main();
